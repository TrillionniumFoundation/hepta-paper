function main() {
  const strict = process.argv.includes('--strict');
  const lock = acquireIntegrationDependencyGateLock();
  if (!lock.ok) {
    process.stdout.write(`${JSON.stringify({
      ok: false,
      status: lock.status,
      gateHash: null,
      blockers: lock.blockers.map((item) => item.code),
      lock: {
        lockDir: relativeToWorkspace(lock.lockDir),
        ownerPid: lock.owner?.pid || null,
        ownerStartedAt: lock.owner?.startedAt || null,
      },
      reportFiles: null,
    }, null, 2)}\n`);
    if (strict) process.exitCode = 1;
    return;
  }
  let lockReleased = false;
  try {
    const gate = buildIntegrationDependencyGate();
    const reportFiles = writeReports(gate);
    lockReleased = releaseIntegrationDependencyGateLock(lock);
    const summary = {
      ok: gate.ok,
      status: gate.status,
      gateHash: gate.gateHash,
      blockers: gate.blockers.map((item) => item.code),
      reportFiles: {
        json: relativeToWorkspace(reportFiles.latestJson),
        md: relativeToWorkspace(reportFiles.latestMd),
      },
    };
    process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
    if (strict && !gate.ok) process.exitCode = 1;
  } finally {
    if (!lockReleased) releaseIntegrationDependencyGateLock(lock);
  }
}

if (isCliEntrypoint(import.meta.url)) main();
