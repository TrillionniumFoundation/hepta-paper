const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const reportsDir = path.join(packageRoot, 'reports');
const defaultGateLockDir = path.join(reportsDir, '.integration-dependency-gate.lock');

export function acquireIntegrationDependencyGateLock({
  lockDir = defaultGateLockDir,
  pid = process.pid,
  startedAt = new Date().toISOString(),
} = {}) {
  return acquireLocalFileLock({
    lockDir,
    pid,
    startedAt,
    owner: {
      command: [process.execPath, ...process.argv.slice(1)],
      cwd: packageRoot,
    },
    acquiredStatus: 'acquired_integration_dependency_gate_lock',
    blockedStatus: 'blocked_integration_dependency_gate_lock',
    busyBlockerCode: 'integration_dependency_gate_already_running',
    busyNotes: (owner) => (owner.pid
      ? `integration dependency gate lock is held by pid ${owner.pid}`
      : 'integration dependency gate lock exists without a live owner record'),
  });
}

export function releaseIntegrationDependencyGateLock(lock = {}) {
  return releaseLocalFileLock(lock);
}

function parseJson(value) {
  try {
    return JSON.parse(value);
  } catch {
    return null;
  }
}

function outputDigest(step) {
  return digest({
    stdout: step.stdout,
    stderr: step.stderr,
    outputJson: step.outputJson,
  });
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch {
    return null;
  }
}

function latestReportHashSummary() {
  return Object.fromEntries(REPORT_FRESHNESS_REQUIRED_REPORTS
    .filter((spec) => spec.gateSummaryHashKey)
    .map((spec) => {
      const report = readJson(path.join(reportsDir, spec.fileId));
      return [spec.gateSummaryHashKey, reportStableHash(report || {})];
    }));
}

function runNodeStep({
  stepId,
  label,
  args,
  parseJsonOutput = false,
}) {
  const startedAt = new Date().toISOString();
  const result = spawnSync(process.execPath, args, {
    cwd: packageRoot,
    encoding: 'utf8',
    maxBuffer: 10 * 1024 * 1024,
  });
  const outputJson = parseJsonOutput ? parseJson(result.stdout) : null;
  const blockers = [];
  if (result.error) {
    blockers.push({
      code: 'step_spawn_failed',
      notes: result.error.message,
    });
  }
  if (result.status !== 0) {
    blockers.push({
      code: 'step_exit_nonzero',
      notes: `${stepId} exited with ${result.status}`,
    });
  }
  if (parseJsonOutput && !outputJson) {
    blockers.push({
      code: 'step_json_output_invalid',
      notes: `${stepId} did not produce parseable JSON stdout`,
    });
  }
  if (outputJson && outputJson.ok === false) {
    blockers.push({
      code: 'step_reported_not_ok',
      notes: `${stepId} reported ok=false`,
    });
  }
  const step = {
    stepId,
    label,
    command: [process.execPath, ...args],
    status: blockers.length ? 'blocked_integration_gate_step' : 'pass_integration_gate_step',
    ok: blockers.length === 0,
    exitCode: result.status,
    signal: result.signal || null,
    outputJson,
    stdout: result.stdout || '',
    stderr: result.stderr || '',
    blockers,
    startedAt,
    finishedAt: new Date().toISOString(),
  };
  return {
    ...step,
    outputHash: outputDigest(step),
  };
}

