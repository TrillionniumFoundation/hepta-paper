function extractPackageRootSymbols(source) {
  const rows = [];
  const namedRegex = /\b(?:import|export)\s*\{([^{}]*)\}\s*from\s*['"]design-production-core['"]/g;
  let match = namedRegex.exec(source.text);
  while (match) {
    const line = lineForIndex(source.text, match.index);
    for (const binding of parseNamedBindings(match[1])) {
      rows.push({
        importKind: 'named',
        importedName: binding.importedName,
        localName: binding.localName,
        moduleHint: moduleHintForSymbol(binding.importedName),
        file: source.file,
        line,
      });
    }
    match = namedRegex.exec(source.text);
  }
  const namespaceRegex = /\bimport\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\s*['"]design-production-core['"]/g;
  match = namespaceRegex.exec(source.text);
  while (match) {
    rows.push({
      importKind: 'namespace',
      importedName: '*',
      localName: match[1],
      moduleHint: null,
      file: source.file,
      line: lineForIndex(source.text, match.index),
    });
    match = namespaceRegex.exec(source.text);
  }
  const defaultRegex = /\bimport\s+([A-Za-z_$][\w$]*)\s+from\s*['"]design-production-core['"]/g;
  match = defaultRegex.exec(source.text);
  while (match) {
    rows.push({
      importKind: 'default',
      importedName: 'default',
      localName: match[1],
      moduleHint: null,
      file: source.file,
      line: lineForIndex(source.text, match.index),
    });
    match = defaultRegex.exec(source.text);
  }
  return rows;
}

