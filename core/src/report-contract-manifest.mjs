function blocker(code, notes, extra = {}) {
  return { code, notes, ...extra };
}

function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function isObject(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function uniqueSorted(values = []) {
  return [...new Set(values.filter(Boolean))].sort((left, right) => left.localeCompare(right));
}

function duplicateValues(values = []) {
  return values
    .filter((value, index, all) => values.indexOf(value) !== index)
    .filter((value, index, all) => all.indexOf(value) === index)
    .sort((left, right) => left.localeCompare(right));
}

function normalizeContract(contract = {}) {
  return {
    contractId: contract.contractId || null,
    label: contract.label || null,
    scriptId: contract.scriptId || null,
    exporterPath: contract.exporterPath || null,
    stepIds: Array.isArray(contract.stepIds) ? [...contract.stepIds] : [],
    fileId: contract.fileId || null,
    stdoutHashField: contract.stdoutHashField || null,
    gateSummaryHashKey: contract.gateSummaryHashKey || null,
    requiredGateArgs: contract.requiredGateArgs ? [...contract.requiredGateArgs] : ['--strict'],
    requiresFreshnessInventory: contract.requiresFreshnessInventory !== false,
  };
}

function fieldBlockers(contract) {
  return REQUIRED_STRING_FIELDS.flatMap((fieldId) => (
    typeof contract[fieldId] === 'string' && contract[fieldId].trim()
      ? []
      : [blocker(
        'report_contract_manifest_required_field_missing',
        `${contract.contractId || 'unknown'} must expose ${fieldId}.`,
        { contractId: contract.contractId || null, fieldId },
      )]
  ));
}

function analyzeContract(contract) {
  const stepIds = Array.isArray(contract.stepIds) ? contract.stepIds : [];
  const blockers = [
    ...(!isObject(contract) ? [blocker(
      'report_contract_manifest_contract_not_object',
      'Each manifest entry must be an object.',
    )] : []),
    ...fieldBlockers(contract),
    ...(!Array.isArray(contract.stepIds) ? [blocker(
      'report_contract_manifest_step_ids_not_array',
      `${contract.contractId || 'unknown'} stepIds must be an array.`,
      { contractId: contract.contractId || null },
    )] : []),
    ...(Array.isArray(contract.stepIds) && stepIds.length === 0 ? [blocker(
      'report_contract_manifest_step_ids_empty',
      `${contract.contractId || 'unknown'} must bind at least one gate step.`,
      { contractId: contract.contractId || null },
    )] : []),
    ...(!String(contract.exporterPath || '').startsWith('src/export-') ? [blocker(
      'report_contract_manifest_exporter_path_invalid',
      `${contract.exporterPath || 'null'} must be an exporter under src/export-*.mjs.`,
      { contractId: contract.contractId || null, exporterPath: contract.exporterPath || null },
    )] : []),
    ...(!String(contract.exporterPath || '').endsWith('.mjs') ? [blocker(
      'report_contract_manifest_exporter_extension_invalid',
      `${contract.exporterPath || 'null'} must be an .mjs module.`,
      { contractId: contract.contractId || null, exporterPath: contract.exporterPath || null },
    )] : []),
    ...(!String(contract.fileId || '').endsWith('-latest.json') ? [blocker(
      'report_contract_manifest_file_id_invalid',
      `${contract.fileId || 'null'} must be a latest JSON report id.`,
      { contractId: contract.contractId || null, fileId: contract.fileId || null },
    )] : []),
    ...(!String(contract.scriptId || '').startsWith('reports:') ? [blocker(
      'report_contract_manifest_script_id_invalid',
      `${contract.scriptId || 'null'} must be a reports:* package script.`,
      { contractId: contract.contractId || null, scriptId: contract.scriptId || null },
    )] : []),
    ...duplicateValues(stepIds).map((stepId) => blocker(
      'report_contract_manifest_duplicate_step_id',
      `${contract.contractId || 'unknown'} repeats stepId ${stepId}.`,
      { contractId: contract.contractId || null, stepId },
    )),
  ];
  return {
    contractId: contract.contractId || null,
    status: blockers.length ? 'blocked_report_contract_manifest_contract' : 'pass_report_contract_manifest_contract',
    ok: blockers.length === 0,
    scriptId: contract.scriptId || null,
    exporterPath: contract.exporterPath || null,
    fileId: contract.fileId || null,
    stepIds,
    stdoutHashField: contract.stdoutHashField || null,
    gateSummaryHashKey: contract.gateSummaryHashKey || null,
    blockers,
  };
}

export function buildReportContractManifestInput({
  manifest = REPORT_CONTRACT_MANIFEST,
  runnerSourceText = '',
} = {}) {
  return {
    manifest: manifest.map(normalizeContract),
    runnerSourceText: String(runnerSourceText || ''),
  };
}

export function analyzeReportContractManifest(input = {}) {
  const manifest = input.manifest || [];
  const runnerSourceText = String(input.runnerSourceText || '');
  const contractAnalyses = manifest.map(analyzeContract);
  const contractIds = manifest.map((contract) => contract.contractId).filter(Boolean);
  const scriptIds = manifest.map((contract) => contract.scriptId).filter(Boolean);
  const exporterPaths = manifest.map((contract) => contract.exporterPath).filter(Boolean);
  const fileIds = manifest.map((contract) => contract.fileId).filter(Boolean);
  const stdoutHashFields = manifest.map((contract) => contract.stdoutHashField).filter(Boolean);
  const gateSummaryHashKeys = manifest.map((contract) => contract.gateSummaryHashKey).filter(Boolean);
  const runnerImportsManifest = /from\s+['"]\.\/report-contract-manifest\.mjs['"]/.test(runnerSourceText);
  const runnerAliasesManifest = /REPORT_RUNNER_CONTRACTS\s*=\s*REPORT_CONTRACT_MANIFEST/.test(runnerSourceText);
  const runnerLocalListPresent = /REPORT_RUNNER_CONTRACTS\s*=\s*Object\.freeze\(\s*\[/.test(runnerSourceText);
  const blockers = [
    ...(!manifest.length ? [blocker(
      'report_contract_manifest_empty',
      'REPORT_CONTRACT_MANIFEST must contain report exporter contracts.',
    )] : []),
    ...duplicateValues(contractIds).map((contractId) => blocker(
      'report_contract_manifest_duplicate_contract_id',
      `${contractId} appears more than once in REPORT_CONTRACT_MANIFEST.`,
      { contractId },
    )),
    ...duplicateValues(scriptIds).map((scriptId) => blocker(
      'report_contract_manifest_duplicate_script_id',
      `${scriptId} appears more than once in REPORT_CONTRACT_MANIFEST.`,
      { scriptId },
    )),
    ...duplicateValues(exporterPaths).map((exporterPath) => blocker(
      'report_contract_manifest_duplicate_exporter_path',
      `${exporterPath} appears more than once in REPORT_CONTRACT_MANIFEST.`,
      { exporterPath },
    )),
    ...duplicateValues(fileIds).map((fileId) => blocker(
      'report_contract_manifest_duplicate_file_id',
      `${fileId} appears more than once in REPORT_CONTRACT_MANIFEST.`,
      { fileId },
    )),
    ...duplicateValues(stdoutHashFields).map((stdoutHashField) => blocker(
      'report_contract_manifest_duplicate_stdout_hash_field',
      `${stdoutHashField} appears more than once in REPORT_CONTRACT_MANIFEST.`,
      { stdoutHashField },
    )),
    ...duplicateValues(gateSummaryHashKeys).map((gateSummaryHashKey) => blocker(
      'report_contract_manifest_duplicate_gate_summary_hash_key',
      `${gateSummaryHashKey} appears more than once in REPORT_CONTRACT_MANIFEST.`,
      { gateSummaryHashKey },
    )),
    ...REQUIRED_CONTRACT_IDS
      .filter((contractId) => !contractIds.includes(contractId))
      .map((contractId) => blocker(
        'report_contract_manifest_required_contract_missing',
        `${contractId} must be present in REPORT_CONTRACT_MANIFEST.`,
        { contractId },
      )),
    ...(!runnerImportsManifest ? [blocker(
      'report_contract_manifest_runner_import_missing',
      'report-runner-contract-regression.mjs must import REPORT_CONTRACT_MANIFEST from report-contract-manifest.mjs.',
    )] : []),
    ...(!runnerAliasesManifest ? [blocker(
      'report_contract_manifest_runner_alias_missing',
      'REPORT_RUNNER_CONTRACTS must alias REPORT_CONTRACT_MANIFEST instead of maintaining a parallel list.',
    )] : []),
    ...(runnerLocalListPresent ? [blocker(
      'report_contract_manifest_runner_local_list_present',
      'report-runner-contract-regression.mjs must not define REPORT_RUNNER_CONTRACTS as a local Object.freeze list.',
    )] : []),
    ...contractAnalyses.flatMap((analysis) => analysis.blockers),
  ];
  return {
    status: blockers.length ? 'blocked_report_contract_manifest_analysis' : 'pass_report_contract_manifest_analysis',
    ok: blockers.length === 0,
    contractCount: manifest.length,
    requiredContractCount: REQUIRED_CONTRACT_IDS.length,
    okContractCount: contractAnalyses.filter((contract) => contract.ok).length,
    stepBindingCount: manifest.reduce((sum, contract) => sum + (contract.stepIds || []).length, 0),
    uniqueStepBindingCount: uniqueSorted(manifest.flatMap((contract) => contract.stepIds || [])).length,
    runnerImportsManifest,
    runnerAliasesManifest,
    runnerLocalListPresent,
    contracts: contractAnalyses,
    blockers,
  };
}

