export function isKnownOpenClawManagedFailureCode(value) {
  return typeof value === 'string'
    && KNOWN_OPENCLAW_MANAGED_FAILURE_CODES.has(value);
}

export function isKnownOpenClawManagedCleanupFailureCode(value) {
  return typeof value === 'string'
    && KNOWN_OPENCLAW_MANAGED_CLEANUP_FAILURE_CODES.has(value);
}

export function projectOpenClawManagedFailureCode(value) {
  const candidate = String(value || '').trim();
  return isKnownOpenClawManagedFailureCode(candidate)
    ? candidate : OPENCLAW_MANAGED_UNCLASSIFIED_FAILURE_CODE;
}
